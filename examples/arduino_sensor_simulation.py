# Function to generate regime-switching continuous sensor signals.
def generate_signals(model, X_train: np.ndarray, duration_s: float, signal_ms: int,
                     dwell_s: float, min_dwell_s: float, tau_s: float,
                     wander: float, noise: float, rng: np.random.Generator):
    """
    Simulate sensors that drift between operating regimes, one per class.

    The regime follows a Markov chain (dwell time min_dwell + exponential).
    Each regime picks a training sample that the model classifies as that
    class (an anchor) and every feature follows an Ornstein-Uhlenbeck process
    pulled toward it, so transitions are smooth and take ~tau seconds.

    Args:
        model: Trained PyRuleAnalyzer model (used to choose anchors).
        X_train (np.ndarray): Training features.
        duration_s (float): Signal length in seconds.
        signal_ms (int): Sensor update period in milliseconds.
        dwell_s (float): Mean time in one regime, seconds.
        min_dwell_s (float): Minimum time in one regime, seconds.
        tau_s (float): Time constant of the transitions, seconds.
        wander (float): Stationary std of the process, in feature stds.
        noise (float): White sensor noise std, in feature stds.
        rng (np.random.Generator): Random generator.

    Returns:
        tuple: (signal (n_steps, n_features), regime label per step,
        list of (time_s, class) regime changes).
    """
    pred = np.asarray(model.predict(X_train)).astype(int).ravel()
    anchors = {c: X_train[pred == c] for c in np.unique(pred)}
    classes = sorted(anchors)
    std = X_train.std(axis=0)
    std = np.where(std > 0, std, 1.0)

    n_steps = int(round(duration_s * 1000 / signal_ms))
    dt = signal_ms / 1000.0
    a = np.exp(-dt / tau_s)
    drive = wander * std * np.sqrt(1 - a * a)

    signal = np.empty((n_steps, X_train.shape[1]))
    label = np.empty(n_steps, dtype=int)
    changes = []

    cls = int(rng.choice(classes))
    target = anchors[cls][rng.integers(len(anchors[cls]))]
    x = target.astype(float).copy()
    next_change = min_dwell_s + rng.exponential(max(dwell_s - min_dwell_s, 1e-9))
    changes.append((0.0, cls))

    for k in range(n_steps):
        t = k * dt
        if t >= next_change and len(classes) > 1:
            cls = int(rng.choice([c for c in classes if c != cls]))
            target = anchors[cls][rng.integers(len(anchors[cls]))]
            next_change = t + min_dwell_s + rng.exponential(max(dwell_s - min_dwell_s, 1e-9))
            changes.append((t, cls))
        x = target + a * (x - target) + drive * rng.standard_normal(x.shape)
        signal[k] = x + noise * std * rng.standard_normal(x.shape)
        label[k] = cls

    return signal, label, changes


