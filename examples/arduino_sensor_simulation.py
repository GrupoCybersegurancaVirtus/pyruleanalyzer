# Function to run the whole simulation from the command line.
def main() -> int:
    """
    Train, export, wire, simulate, compare and plot.

    Returns:
        int: Process exit code (0 pass, 1 fail).
    """
    p = argparse.ArgumentParser(
        description='Run a pyruleanalyzer Arduino sketch on simulated continuous sensors.',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog='Read the docstring at the top of this file for the details.')

    g = p.add_argument_group('data and model')
    g.add_argument('--dataset', default='iris',
                   choices=['iris', 'wine', 'breast_cancer', 'digits'])
    g.add_argument('--csv', default=None, help='your own CSV')
    g.add_argument('--target', default='Target', help='target column of --csv')
    g.add_argument('--model', default='Decision Tree',
                   choices=['Decision Tree', 'Random Forest',
                            'Gradient Boosting Decision Trees'])
    g.add_argument('--n-estimators', type=int, default=None)
    g.add_argument('--max-depth', type=int, default=6)
    g.add_argument('--board', default='uno', help='board for the memory check')
    g.add_argument('--seed', type=int, default=42)

    g = p.add_argument_group('signals')
    g.add_argument('--duration', type=float, default=120.0, help='seconds of signal')
    g.add_argument('--signal-ms', type=int, default=10, help='sensor update period (ms)')
    g.add_argument('--sample-ms', type=int, default=250,
                   help='SAMPLE_INTERVAL_MS of the sketch (ms)')
    g.add_argument('--dwell', type=float, default=15.0, help='mean seconds per regime')
    g.add_argument('--min-dwell', type=float, default=5.0, help='minimum seconds per regime')
    g.add_argument('--tau', type=float, default=1.5, help='transition time constant (s)')
    g.add_argument('--wander', type=float, default=0.15,
                   help='process std around the regime, in feature stds')
    g.add_argument('--noise', type=float, default=0.03,
                   help='white sensor noise std, in feature stds')
    g.add_argument('--adc-bits', type=int, default=10)

    g = p.add_argument_group('output')
    g.add_argument('--output-dir', default='files/sim')
    g.add_argument('--name', default='sim_model')
    g.add_argument('--plot-features', type=int, default=4)
    g.add_argument('--min-parity', type=float, default=100.0)
    args = p.parse_args()

    rng = np.random.default_rng(args.seed)
    os.makedirs(args.output_dir, exist_ok=True)

    print('=' * 62)
    print('CONTINUOUS-SENSOR SIMULATION -- pyruleanalyzer Arduino sketch')
    print('=' * 62)

    # ---------- 1. train + export the production sketch ----------
    print('\n[1/5] Training and export')
    import pandas as pd
    from pyruleanalyzer import full_pipeline

    csv_path, target, _ = load_dataset(args.dataset, args.csv, args.target, args.output_dir)
    train_csv, test_csv = split_holdout(csv_path, target, 0.3, args.seed, args.output_dir)
    params = dict(train_csv=train_csv, test_csv=test_csv, target_feature=target,
                  model_type=args.model, max_depth=args.max_depth,
                  output_dir=args.output_dir, output_name=args.name,
                  generate_arduino_sketch=True, board_model=args.board,
                  memory_report=True, random_seed=args.seed)
    if args.n_estimators is not None:
        params['n_estimators'] = args.n_estimators
    results = full_pipeline(**params)
    model = results['model']
    ino_path = results['generated_files'].get('arduino')
    if not ino_path or not os.path.exists(ino_path):
        raise SystemExit('[!] full_pipeline produced no .ino.')

    train_df = pd.read_csv(train_csv)
    X_train = train_df.drop(columns=[target]).values.astype(float)
    feature_names = list(getattr(model.classifier, '_array_feature_names', None)
                         or train_df.drop(columns=[target]).columns)
    n_classes = int(max(train_df[target].astype(int).max() + 1,
                        len(np.unique(train_df[target]))))

    # ---------- 2. wire the sketch to the ADC ----------
    print('\n[2/5] Sensor wiring')
    sensors = SensorMap(X_train, adc_bits=args.adc_bits)
    sketch_name = f'{args.name}_sim'
    sketch_dir = os.path.join(args.output_dir, sketch_name)
    os.makedirs(sketch_dir, exist_ok=True)
    sketch_file = f'{sketch_name}.ino'
    with open(ino_path, 'r', encoding='utf-8') as f:
        wired = wire_sketch(f.read(), sensors, feature_names, args.sample_ms)
    with open(os.path.join(sketch_dir, sketch_file), 'w', encoding='utf-8') as f:
        f.write(wired)
    n_dig = int(sensors.digital.sum())
    print(f'  {len(feature_names)} channels ({len(feature_names) - n_dig} analog '
          f'{args.adc_bits}-bit, {n_dig} digital), SAMPLE_INTERVAL_MS={args.sample_ms}')
    print(f'  sketch: {os.path.join(sketch_dir, sketch_file)}')

    # ---------- 3. generate the signals ----------
    print('\n[3/5] Signals')
    signal, label, changes = generate_signals(
        model, X_train, args.duration, args.signal_ms, args.dwell, args.min_dwell,
        args.tau, args.wander, args.noise, rng)
    counts = sensors.to_counts(signal)
    signals_path = os.path.join(args.output_dir, f'{args.name}_signals.txt')
    write_signals(signals_path, counts, args.signal_ms)
    print(f'  {args.duration:.0f} s, {len(counts):,} steps of {args.signal_ms} ms, '
          f'{len(changes) - 1} regime changes')

    # ---------- 4. run the sketch on the PC ----------
    print('\n[4/5] Running setup()/loop() with g++ + Arduino shim')
    t_ms, y_sketch, feats, serial = run_sketch(sketch_dir, sketch_file,
                                               os.path.abspath(signals_path))
    print(f'  {len(t_ms)} loop() iterations; serial banner: '
          f'{" / ".join(serial[:2]) if serial else "(none)"}')

    # Python reference on the same ADC counts
    step = np.minimum(t_ms // args.signal_ms, len(counts) - 1).astype(int)
    feats_py = sensors.to_values(counts[step])
    features_exact = bool(np.array_equal(feats_py, feats))
    y_py = np.asarray(model.predict(feats)).astype(int).ravel()
    y_true = label[step]
    t_s = t_ms / 1000.0

    # ---------- 5. metrics, timeline, plot ----------
    print('\n[5/5] Comparison')
    metrics = timeline_metrics(t_s, y_true, y_sketch, y_py, changes, settle_s=3 * args.tau)
    passed = features_exact and metrics['parity_percent'] >= args.min_parity

    timeline_path = os.path.join(args.output_dir, f'{args.name}_timeline.csv')
    pd.DataFrame({'time_s': t_s, 'true_regime': y_true, 'sketch': y_sketch,
                  'python': y_py,
                  **{name: feats[:, i] for i, name in enumerate(feature_names)}}
                 ).to_csv(timeline_path, index=False)

    plot_path = os.path.join(args.output_dir, f'{args.name}_timeline.png')
    plot_idx = most_used_features(model, len(feature_names),
                                  min(args.plot_features, len(feature_names)))
    plot_timeline(plot_path, np.arange(len(counts)) * args.signal_ms / 1000.0,
                  sensors.to_values(counts), t_s, feats, y_true, y_sketch, y_py,
                  changes, feature_names, plot_idx, n_classes,
                  f'{args.model} -- sketch on simulated sensors '
                  f'({args.sample_ms} ms sampling, {args.adc_bits}-bit ADC)')

    report = {
        'model': args.model, 'dataset': args.csv or args.dataset,
        'sketch': os.path.join(sketch_dir, sketch_file),
        'signal': {'duration_s': args.duration, 'signal_ms': args.signal_ms,
                   'sample_ms': args.sample_ms, 'dwell_s': args.dwell,
                   'min_dwell_s': args.min_dwell, 'tau_s': args.tau,
                   'wander': args.wander, 'noise': args.noise,
                   'adc_bits': args.adc_bits, 'seed': args.seed},
        'features_bit_exact': features_exact,
        **metrics,
        'passed': passed,
    }
    report_path = os.path.join(args.output_dir, f'{args.name}_report.json')
    with open(report_path, 'w', encoding='utf-8') as f:
        json.dump(report, f, indent=2)

    lat = metrics['detection_latency_s']
    print(f'  features sketch == Python (bit-exact): {features_exact}')
    print(f'  parity sketch vs Python : {metrics["parity_percent"]:.2f}% '
          f'({metrics["parity_mismatches"]} mismatches)')
    print(f'  accuracy vs true regime : {metrics["accuracy_percent"]:.2f}% '
          f'(settled, >= {3 * args.tau:.1f} s after a change: '
          f'{metrics["settled_accuracy_percent"]:.2f}%)'
          if metrics['settled_accuracy_percent'] is not None else '')
    print(f'  class flips             : {metrics["class_flips"]} '
          f'({metrics["regime_changes"]} regime changes, '
          f'{metrics["spurious_flips"]} beyond them)')
    if lat:
        print(f'  detection latency       : mean {lat["mean"]:.2f} s, max {lat["max"]:.2f} s'
              f' ({metrics["regimes_never_detected"]} regimes never detected)')
    print(f'\n  timeline: {timeline_path}\n  plot    : {plot_path}\n  report  : {report_path}')
    print(f'\nRESULT: {"PASS" if passed else "FAIL"}')
    return 0 if passed else 1


if __name__ == '__main__':
    sys.exit(main())
