# Function to compute the timeline metrics.
def timeline_metrics(t_s, y_true, y_sketch, y_py, changes, settle_s):
    """
    Parity, accuracy and temporal behaviour of the classification.

    Args:
        t_s (np.ndarray): Time of each loop(), seconds.
        y_true (np.ndarray): True regime at each loop().
        y_sketch (np.ndarray): Class printed by the sketch.
        y_py (np.ndarray): Python prediction on the same features.
        changes (list): (time_s, class) regime changes.
        settle_s (float): Window after a change excluded from settled accuracy.

    Returns:
        dict: Metrics.
    """
    change_times = np.array([c[0] for c in changes])
    since_change = t_s - change_times[np.searchsorted(change_times, t_s, side='right') - 1]
    settled = since_change >= settle_s

    latencies, missed = [], 0
    for i, (tc, cls) in enumerate(changes[1:], start=1):
        end = changes[i + 1][0] if i + 1 < len(changes) else np.inf
        hit = np.where((t_s >= tc) & (t_s < end) & (y_sketch == cls))[0]
        if len(hit):
            latencies.append(float(t_s[hit[0]] - tc))
        else:
            missed += 1

    flips = int(np.sum(y_sketch[1:] != y_sketch[:-1]))
    return {
        'loop_iterations': int(len(t_s)),
        'parity_percent': float(100.0 * np.mean(y_sketch == y_py)),
        'parity_mismatches': int(np.sum(y_sketch != y_py)),
        'accuracy_percent': float(100.0 * np.mean(y_sketch == y_true)),
        'settled_accuracy_percent': (float(100.0 * np.mean(y_sketch[settled] == y_true[settled]))
                                     if settled.any() else None),
        'regime_changes': len(changes) - 1,
        'class_flips': flips,
        'spurious_flips': max(0, flips - (len(changes) - 1)),
        'detection_latency_s': ({'mean': float(np.mean(latencies)),
                                 'max': float(np.max(latencies))} if latencies else None),
        'regimes_never_detected': missed,
    }


# Function to rank features by how many rule conditions test them.
def most_used_features(model, n_features: int, k: int):
    """
    Pick the k features that appear most often in the rule conditions.

    Args:
        model: PyRuleAnalyzer model.
        n_features (int): Number of features.
        k (int): How many to return.

    Returns:
        list: Feature indices.
    """
    counts = np.zeros(n_features)
    try:
        clf = model.classifier
        names = list(clf._array_feature_names)
        rules = clf.final_rules or clf.initial_rules
        for rule in rules:
            for cond in rule.parsed_conditions or []:
                if cond[0] in names:
                    counts[names.index(cond[0])] += 1
    except Exception:
        pass
    return [int(i) for i in np.argsort(-counts, kind='stable')[:k]]


# Function to draw the timeline figure.
def plot_timeline(path, sig_t, signal_values, t_s, feats, y_true, y_sketch, y_py,
                  changes, feature_names, plot_idx, n_classes, title):
    """
    Signals of the most used features over the true regime, and the classes.

    Args:
        path (str): Output PNG.
        sig_t (np.ndarray): Signal time axis, seconds.
        signal_values (np.ndarray): Quantized signal in physical units.
        t_s (np.ndarray): loop() times, seconds.
        feats (np.ndarray): Features read by the sketch at each loop().
        y_true, y_sketch, y_py (np.ndarray): Classes per loop().
        changes (list): (time_s, class) regime changes.
        feature_names (list): Feature names.
        plot_idx (list): Features to draw.
        n_classes (int): Number of classes.
        title (str): Figure title.
    """
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    colors = plt.get_cmap('tab10')
    end = sig_t[-1] if len(sig_t) else 0
    spans = [(tc, changes[i + 1][0] if i + 1 < len(changes) else end, c)
             for i, (tc, c) in enumerate(changes)]

    n = len(plot_idx)
    fig, axes = plt.subplots(n + 1, 1, figsize=(13, 1.7 * n + 2.6), sharex=True,
                             gridspec_kw={'height_ratios': [1] * n + [1.4]})
    for ax, j in zip(axes[:-1], plot_idx):
        for a, b, c in spans:
            ax.axvspan(a, b, color=colors(c % 10), alpha=0.10, lw=0)
        ax.plot(sig_t, signal_values[:, j], lw=0.7, color='0.35')
        ax.plot(t_s, feats[:, j], '.', ms=2.5, color='black')
        ax.set_ylabel(feature_names[j], fontsize=8, rotation=0, ha='right', va='center')
        ax.tick_params(labelsize=7)

    ax = axes[-1]
    for a, b, c in spans:
        ax.axvspan(a, b, color=colors(c % 10), alpha=0.10, lw=0)
    ax.step(t_s, y_true, where='post', color='0.5', lw=3, alpha=0.6, label='true regime')
    ax.step(t_s, y_py, where='post', color='tab:blue', lw=1.2, label='Python model.predict')
    ax.plot(t_s, y_sketch, '.', ms=3, color='black', label='sketch on the PC')
    bad = y_sketch != y_py
    if bad.any():
        ax.plot(t_s[bad], y_sketch[bad], 'x', ms=8, color='red', label='sketch != Python')
    ax.set_yticks(range(n_classes))
    ax.set_ylabel('class', fontsize=8)
    ax.set_xlabel('time (s)')
    ax.legend(fontsize=7, loc='upper right', ncol=4)
    ax.tick_params(labelsize=7)

    fig.suptitle(title, fontsize=10)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)


