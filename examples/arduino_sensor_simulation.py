# 2. SENSOR WIRING (replaces the placeholder read_features())
# ==============================================================================

# Class holding the ADC mapping of every feature.
class SensorMap:
    """
    Linear ADC mapping per feature: value = lo + counts * scale.

    Args:
        X_train (np.ndarray): Training features, used to size each channel.
        adc_bits (int): ADC resolution.
        margin (float): Extra range on each side, as a fraction of the span.
    """

    # Method to build the ADC mapping from the training data.
    def __init__(self, X_train: np.ndarray, adc_bits: int = 10, margin: float = 0.1):
        """
        Size every channel to the training range plus a margin.

        Args:
            X_train (np.ndarray): Training features.
            adc_bits (int): ADC resolution in bits.
            margin (float): Extra range on each side, as a fraction of the span.
        """
        self.max_counts = (1 << adc_bits) - 1
        lo = X_train.min(axis=0).astype(float)
        hi = X_train.max(axis=0).astype(float)
        span = np.where(hi > lo, hi - lo, 1.0)
        self.digital = np.array([set(np.unique(col)) <= {0.0, 1.0}
                                 for col in X_train.T.astype(float)])
        self.lo = np.where(self.digital, 0.0, lo - margin * span)
        self.scale = np.where(self.digital, 1.0,
                              (span * (1 + 2 * margin)) / self.max_counts)

    # Method to convert physical values into ADC counts (or 0/1 for digital pins).
    def to_counts(self, values: np.ndarray) -> np.ndarray:
        """
        Quantize physical values the way the board's ADC would.

        Args:
            values (np.ndarray): Signal, shape (n_steps, n_features).

        Returns:
            np.ndarray: Integer counts, same shape.
        """
        counts = np.rint((values - self.lo) / self.scale)
        counts = np.clip(counts, 0, self.max_counts).astype(int)
        digital = (values > 0.5).astype(int)
        return np.where(self.digital, digital, counts)

    # Method to convert ADC counts into the values read_features() computes.
    def to_values(self, counts: np.ndarray) -> np.ndarray:
        """
        Same arithmetic as the generated read_features(), in double precision.

        Args:
            counts (np.ndarray): Integer counts.

        Returns:
            np.ndarray: Feature values seen by the sketch.
        """
        analog = self.lo + counts.astype(float) * self.scale
        return np.where(self.digital, counts.astype(float), analog)

    # Method to emit the C read_features() for this mapping.
    def c_code(self, feature_names) -> str:
        """
        Generate the read_features() that replaces the sketch placeholder.

        Args:
            feature_names (list): Feature names in model order.

        Returns:
            str: C source.
        """
        n = len(self.lo)
        lo = ', '.join(repr(float(v)) for v in self.lo)
        scale = ', '.join(repr(float(v)) for v in self.scale)
        dig = ', '.join(str(int(v)) for v in self.digital)
        wiring = '\n'.join(
            f'//   A0+{i:<3d} {"digital" if self.digital[i] else "analog "}  {name}'
            for i, name in enumerate(feature_names))
        return (
            '// ============================================================\n'
            '// Sensor wiring (generated by examples/arduino_sensor_simulation.py)\n'
            '// feature i <- pin A0+i; analog: value = SENSOR_LO[i] + counts * SENSOR_SCALE[i]\n'
            + wiring + '\n'
            + (f'// NOTE: {n} channels; an Uno has 6 analog inputs (use a Mega or a mux).\n'
               if n > 6 else '')
            + '// ============================================================\n'
            f'static const double SENSOR_LO[N_FEATURES] = {{{lo}}};\n'
            f'static const double SENSOR_SCALE[N_FEATURES] = {{{scale}}};\n'
            f'static const uint8_t SENSOR_DIGITAL[N_FEATURES] = {{{dig}}};\n'
            '\n'
            'void read_features(void) {\n'
            '    for (int i = 0; i < N_FEATURES; i++) {\n'
            '        if (SENSOR_DIGITAL[i])\n'
            '            features[i] = digitalRead(A0 + i) == HIGH ? 1.0 : 0.0;\n'
            '        else\n'
            '            features[i] = SENSOR_LO[i] + analogRead(A0 + i) * SENSOR_SCALE[i];\n'
            '    }\n'
            '}\n'
        )


# Function to turn the production .ino into the sensor-wired sketch.
def wire_sketch(ino_text: str, sensors: SensorMap, feature_names, sample_ms: int) -> str:
    """
    Replace the placeholder read_features() and the sampling period.

    Args:
        ino_text (str): Production sketch from export_to_arduino_ino().
        sensors (SensorMap): ADC mapping.
        feature_names (list): Feature names in model order.
        sample_ms (int): New SAMPLE_INTERVAL_MS.

    Returns:
        str: Sketch source.
    """
    pattern = re.compile(r'void read_features\(void\) \{.*?\n\}\n', re.S)
    if not pattern.search(ino_text):
        raise SystemExit('[!] read_features() placeholder not found -- generate the sketch '
                         'with include_sensor_placeholders=True.')
    text = pattern.sub(lambda _: sensors.c_code(feature_names), ino_text, count=1)
    text, n = re.subn(r'#define SAMPLE_INTERVAL_MS \d+',
                      f'#define SAMPLE_INTERVAL_MS {sample_ms}', text)
    if n != 1:
        raise SystemExit('[!] SAMPLE_INTERVAL_MS not found in the sketch.')
    return text


