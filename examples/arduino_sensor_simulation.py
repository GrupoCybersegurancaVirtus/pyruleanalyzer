"""
Continuous-sensor simulation of a pyruleanalyzer Arduino sketch, on the PC.

The HIL runner (`arduino_hardware_test.py`) checks the exported engine one
vector at a time. This script checks it the way it runs in the field: the
board samples sensors whose signals evolve continuously in time, classifies
every SAMPLE_INTERVAL_MS and prints the class over the serial port.

No board is needed. The production sketch's own setup()/loop() run unchanged on
the PC, compiled with g++ against a small Arduino shim (virtual clock,
analogRead/digitalRead served from a recorded signal, Serial printing to
stdout). Only read_features() is replaced, by a version that reads the analog
channels and converts ADC counts to physical units -- the same function that a
real deployment has to write, so the generated .ino also builds for a real
board with arduino-cli.

===============================================================================
 HOW IT WORKS
===============================================================================

    signal generator (Python)          sketch on the PC (g++ + shim)
    -------------------------          -----------------------------
    regime = class c (Markov chain,     loop():
      random dwell time)                  read_features()  -> analogRead(A0+i)
    feature i: Ornstein-Uhlenbeck         pyra_predict(features)
      process pulled toward a training    Serial.print({"class": ...})
      sample of class c                   delay(SAMPLE_INTERVAL_MS)
    + sensor noise                                    |
    -> ADC counts (10 bit) per channel  <--- virtual clock: analogRead returns
       every --signal-ms                     the counts at the current millis()

Then, for every loop() iteration, the script compares:
    * the class the sketch printed vs model.predict() on the exact features
      the sketch used (parity, must be 100%);
    * the features the sketch used vs the ones Python computes from the same
      ADC counts (the sensor conversion is bit-exact);
    * the class vs the true regime (accuracy, settled accuracy, detection
      latency after each regime change, spurious class flips).

and draws the timeline: the signals of the most used features over the true
regime, and the true / Python / sketch class over time.

Binary features (only 0 and 1 in the data) are wired as digital pins: the
process crosses 0.5 with noise, so transitions chatter like a real switch.

Time is virtual: delay() advances the clock and nothing else does, so the
"(N us)" the sketch prints is 0 here. Inference latency on the target is
measured by the HIL runner on a real board.

USAGE
-----
    python examples/arduino_sensor_simulation.py
    python examples/arduino_sensor_simulation.py --dataset wine --model "Random Forest" \
        --n-estimators 10 --duration 300 --sample-ms 200
    python examples/arduino_sensor_simulation.py --csv examples/data/covid_train.csv \
        --target <target column> --noise 0.1

Outputs (in --output-dir, default files/sim):
    <name>_sim/<name>_sim.ino   sketch with ADC wiring (builds with arduino-cli)
    <name>_sim/arduino_shim.h   Arduino API shim for the PC
    <name>_signals.txt          ADC counts fed to the sketch
    <name>_timeline.csv         one row per loop(): time, true class, sketch, Python
    <name>_timeline.png         timeline plot
    <name>_report.json          metrics

Exit code 0 when parity and the feature check pass, 1 otherwise.

Requirements: the project (sklearn, pandas, numpy, matplotlib) + g++ in PATH.
"""
