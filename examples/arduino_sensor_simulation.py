# Function to compile the wired sketch with the shim and run it on the signal.
def run_sketch(sketch_dir: str, sketch_file: str, signals_path: str):
    """
    Compile <sketch_file> + shim with g++ and run it on the recorded signal.

    Args:
        sketch_dir (str): Directory with the .ino.
        sketch_file (str): .ino file name.
        signals_path (str): Signal file written by write_signals().

    Returns:
        tuple: (times_ms, sketch classes, feature buffers, serial log lines).
    """
    gpp = shutil.which('g++') or shutil.which('clang++')
    if not gpp:
        raise SystemExit('[!] g++ not found in PATH.')

    with open(os.path.join(sketch_dir, 'arduino_shim.h'), 'w', encoding='utf-8') as f:
        f.write(ARDUINO_SHIM)
    main_src = os.path.join(sketch_dir, 'sim_main.cpp')
    with open(main_src, 'w', encoding='utf-8') as f:
        f.write(SIM_MAIN % {'sketch': sketch_file})
    exe = os.path.join(sketch_dir, 'sim.exe' if os.name == 'nt' else 'sim')

    # -ffp-contract=off: no fused multiply-add, so lo + counts*scale rounds
    # exactly like numpy; -w: infinite thresholds are emitted as 1e500
    cp = subprocess.run([gpp, '-O2', '-w', '-ffp-contract=off', '-o', exe, main_src],
                        capture_output=True, text=True)
    if cp.returncode != 0:
        print(cp.stderr[-3000:])
        raise SystemExit('[!] g++ could not compile the sketch.')

    run = subprocess.run([exe, signals_path], capture_output=True, text=True)
    if run.returncode != 0:
        raise SystemExit(f'[!] simulation exited with {run.returncode}: {run.stderr[-500:]}')

    times, classes, feats, serial = [], [], [], []
    cur_t, cur_c = None, None
    for line in run.stdout.splitlines():
        if line.startswith('#T '):
            cur_t, cur_c = int(line[3:]), None
        elif line.startswith('#X '):
            times.append(cur_t)
            classes.append(cur_c if cur_c is not None else -1)
            feats.append([float(v) for v in line[3:].split(',')])
        else:
            serial.append(line)
            m = re.match(r'\{"class":(-?\d+)', line)
            if m:
                cur_c = int(m.group(1))
    return np.array(times), np.array(classes), np.array(feats), serial


# Function to write the ADC counts in the format the shim reads.
def write_signals(path: str, counts: np.ndarray, signal_ms: int) -> None:
    """
    Write "<steps> <channels> <signal_ms>" followed by one row of counts per step.

    Args:
        path (str): Output file.
        counts (np.ndarray): Counts, shape (n_steps, n_features).
        signal_ms (int): Sensor update period in milliseconds.
    """
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'{counts.shape[0]} {counts.shape[1]} {signal_ms}\n')
        np.savetxt(f, counts, fmt='%d')


